import assert from 'node:assert/strict';
import {physicalAnatomy,sourceClass,multiplicity}
 from '../src/labLaloAnatomiaSinPuestoVT3';
import {buildSheet} from '../src/sheet';
import {diaVacio} from '../src/domain';
import {formPositions} from '../src/motorFormasPrimero';
const prev=diaVacio();
prev.Nocturno={...Object.fromEntries(['Ciudad','Provincia','Córdoba','Santa Fé','Entre Ríos','Montevideo'].map(x=>[x,'1234']))} as any;
const current=diaVacio();
current.Previa={...prev.Nocturno};
const sheet=buildSheet(current,prev);
const pre=formPositions(sheet,'Previa');
const p=physicalAnatomy(sheet,'Previa',pre);
assert(p.length>0);
assert(p.every(x=>x.frontier==='UNICA_COLUMNA'));
assert(p.every(x=>x.sourceCount===1&&x.pathCount>=1));
const older=formPositions(sheet,'Primera');
const two=physicalAnatomy(sheet,'Primera',older);
assert(two.length>=p.length);
assert(two.every(x=>x.frontier==='SOLO_NUEVA'||x.frontier==='SOLO_ANTIGUAS'||x.frontier==='NUEVA_Y_ANTIGUAS'));
// Las dos columnas de esta prueba repiten sus cifras; no exigir exclusivos.
assert(two.every(x=>x.pathCount>=x.sourceCount));
assert(two.every(x=>x.members===1||x.members===2));
assert(two.every(x=>x.expectedHeadHitsPerJur===x.members/1000));
assert(two.every(x=>x.sourceIds.every(s=>s==='prevNocturno'||s==='Previa')));
assert.equal(sourceClass(['prevNocturno'],'Nocturno'),'SOLO_ANTIGUAS');
assert.equal(sourceClass(['Vespertino'],'Nocturno'),'SOLO_NUEVA');
assert.equal(sourceClass(['Vespertino','Previa'],'Nocturno'),'NUEVA_Y_ANTIGUAS');
assert.equal(multiplicity(1),'UN_CAMINO');
assert.equal(multiplicity(3),'DOS_TRES');
assert.equal(multiplicity(4),'CUATRO_MAS');
assert.throws(()=>physicalAnatomy(sheet,'Previa',[...older.filter(x=>x.source==='Previa')]),/FUGA/);
console.log('LALO_ANATOMIA_VT3_TEST_OK');
