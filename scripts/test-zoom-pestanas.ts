import assert from 'node:assert/strict';
import {ZOOM_TABS,ZOOM_MAX,ZOOM_MIN,clampZoom,defaultZoomLevels,applyTabZoom,decodeTabZoom} from '../src/tabZoom';

assert.deepEqual(ZOOM_TABS,['hoja','predictiva','prediccion','papa','cabezas','info']);
assert.equal(ZOOM_MIN,1);
assert.equal(ZOOM_MAX,2.5);
assert.equal(clampZoom(.5),1);
assert.equal(clampZoom(50),2.5);
assert.equal(clampZoom(1.9876),1.99);
assert.equal(clampZoom(Number.NaN),1);
assert.equal(clampZoom(Number.POSITIVE_INFINITY),1);
const initial=defaultZoomLevels();
assert.equal(Object.values(initial).filter(v=>v===1).length,6);
const zoomHoja=applyTabZoom(initial,'hoja',2.3);
assert.equal(zoomHoja.hoja,2.3);
assert.equal(zoomHoja.papa,1,'Zoom de Hoja no altera la pestaña Papá');
assert.equal(initial.hoja,1,'No hay mutación del estado original');
const zoomPapa=applyTabZoom(zoomHoja,'papa',1.75);
assert.equal(zoomPapa.hoja,2.3);
assert.equal(zoomPapa.papa,1.75);
assert.equal(zoomPapa.cabezas,1);
const restored=decodeTabZoom(JSON.stringify({...zoomPapa,extra:100,info:9}));
assert.equal(restored.hoja,2.3);
assert.equal(restored.papa,1.75);
assert.equal(restored.info,2.5);
assert.equal(decodeTabZoom('broken').hoja,1);
assert.equal(decodeTabZoom('null').info,1);
assert.equal(decodeTabZoom(JSON.stringify({hoja:'9',prediccion:0.2})).hoja,1);
assert.equal(decodeTabZoom(JSON.stringify({prediccion:0.2})).prediccion,1);
console.log('ZOOM_TABS_OK: escala 100-250%, seis pestañas independientes, reset e historial seguro');
