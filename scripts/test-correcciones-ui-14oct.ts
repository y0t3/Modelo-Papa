import assert from 'node:assert/strict';
import {clampPanX,pinchAtX,clampZoom,defaultZoomLevels} from '../src/tabZoom';
import {describeBoardCell} from '../src/boardFocus';
import type {PanoramaKind} from '../src/panoramaModel';

const width=360;
assert.equal(clampPanX(0,2,width),0);
assert.equal(clampPanX(-100,2,width),-100);
assert.equal(clampPanX(-360,2,width),-360);
assert.equal(clampPanX(-420,2,width),-360,'Se debe poder llegar al borde DERECHO del contenido');
assert.equal(clampPanX(+55,2,width),0,'Borde izquierdo limitado');
assert.equal(clampPanX(-150,1,width),0,'Zoom 100 % no debe permitir arrastre lateral');
assert.equal(clampPanX(-150,2.5,width),-150);
assert.equal(pinchAtX(0,1,2,180,width),-180,'El pellizco al centro mantiene su punto de interés');
assert.equal(pinchAtX(0,1,2,330,width),-330,'El pellizco a derecha se acerca a ese sector');
assert.equal(pinchAtX(-300,2,1,330,width),0,'Zoom 100 % restablece el desplazamiento lateral');
assert.equal(clampZoom(1),1);
assert.equal(defaultZoomLevels().papa,1,'Las claves de Zoom en AsyncStorage se mantienen para no perder preferencias');
const any=describeBoardCell(['vt2','vt3','vt4'],[],false);
assert.deepEqual(any.visibleKinds,['vt2','vt3','vt4']);
assert.equal(any.focus,false);assert.equal(any.muted,false);
const turn=describeBoardCell(['vt2','vt3'],[],true);
assert.deepEqual(turn.visibleKinds,['vt2','vt3'],'Las marcas de otros turnos permanecen');
assert.equal(turn.muted,true,'Las marcas ajenas se dibujan atenuadas');
const selected=describeBoardCell(['vt2','vt3'],['vt2'],true);
assert.deepEqual(selected.visibleKinds,['vt2','vt3'],'También preservar trazos que comparten casillas');
assert.deepEqual(selected.emphasisKinds,['vt2']);
assert.equal(selected.focus,true);assert.equal(selected.muted,false);
const head=describeBoardCell(['vt4'],['vt4'],true);
assert.equal(head.focus,true);assert.equal(head.muted,false);
const unmarked=describeBoardCell([] ,[],true);
assert.equal(unmarked.muted,false);
console.log('CORRECCIONES_UI_OK: paneo horizontal en ambos extremos, foco de pellizco y marcas tenues persistentes');
